# Builds src/lib/server/firm-networks.ts: the address ranges of the networks listed in
# tools/firm-networks.json, so the server can tell that a visit came from, say, a Goldman Sachs office
# network without keeping the address or sending it anywhere.
# Usage (the data is public domain, from https://iptoasn.com; download both files first):
#   python3 tools/import-firm-networks.py <folder with ip2asn-v4.tsv.gz and ip2asn-v6.tsv.gz>
# Re-run it every few months: firms add and move address ranges.
import gzip
import ipaddress
import json
import os
import sys

if len(sys.argv) != 2:
    sys.exit("Usage: python3 tools/import-firm-networks.py <folder with ip2asn-v4.tsv.gz and ip2asn-v6.tsv.gz>")
folder = sys.argv[1]
firms = json.load(open("tools/firm-networks.json", encoding="utf-8"))["firms"]
names = sorted(firms, key=str.lower)
owner = {asn: names.index(name) for name, asns in firms.items() for asn in asns}

ranges = {4: [], 6: []}
for version in (4, 6):
    width = 8 if version == 4 else 32
    with gzip.open(os.path.join(folder, f"ip2asn-v{version}.tsv.gz"), "rt", encoding="utf-8", errors="replace") as data:
        for line in data:
            start, end, asn = line.split("\t")[:3]
            firm = owner.get(int(asn))
            if firm is None:
                continue
            # Addresses as fixed-width hex, so ranges compare as plain strings.
            hexed = [format(int(ipaddress.ip_address(a)), f"0{width}x") for a in (start, end)]
            ranges[version].append((*hexed, firm))
    ranges[version].sort()

found = {names[f] for v in ranges.values() for *_, f in v}
missing = sorted(set(names) - found)


def rows(version):
    return "\n".join(f'  ["{a}", "{b}", {f}],' for a, b, f in ranges[version])


with open("src/lib/server/firm-networks.ts", "w", encoding="utf-8") as out:
    out.write(
        "// Generated by tools/import-firm-networks.py from tools/firm-networks.json and iptoasn.com data.\n"
        "// Do not edit by hand. Each row: first address, last address (fixed-width hex), firm.\n\n"
        f"export const FIRMS: string[] = {json.dumps(names, ensure_ascii=False)};\n\n"
        f"export const V4: [string, string, number][] = [\n{rows(4)}\n];\n\n"
        f"export const V6: [string, string, number][] = [\n{rows(6)}\n];\n"
    )
print(f"Wrote {len(ranges[4])} IPv4 and {len(ranges[6])} IPv6 ranges for {len(found)} firms to src/lib/server/firm-networks.ts")
if missing:
    print("No ranges found for:", ", ".join(missing))
