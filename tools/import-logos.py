# Builds the site's firm logos from a logo pack (Vasco's, in the club Drive) and writes src/data/logos.ts.
# Usage:
#   python3 tools/import-logos.py "<pack>/logos" [<more logo folders>...]
# Each further folder (for example logos downloaded later, club Drive content/2026-11-05/logos-added)
# has its own logos.json in the same format and adds to the pack, or replaces a logo of the same name.
# The pack holds each logo as a 2400 px transparent PNG (plus an SVG) and logos.json, which maps each firm's
# name, exactly as members.ts and departments.ts spell it, to its file. Each PNG is trimmed to the logo
# (the pack adds an even margin, which would make wide wordmarks look smaller than square marks at the same
# height), scaled to 400 px on its longer side and saved as lossless WebP, so nothing is recoloured or
# cropped. Needs Pillow (pip install pillow).
import json
import os
import sys

from PIL import Image

if len(sys.argv) < 2:
    sys.exit('Usage: python3 tools/import-logos.py "<pack>/logos" [<more logo folders>...]')
OUT_DIR = "public/images/logos"
# The site shows a logo at most about 190 px wide, so 400 px covers sharp (2x) screens.
LONGEST = 400
os.makedirs(OUT_DIR, exist_ok=True)

# Every logo by firm name (a later folder's replaces an earlier one's), and every firm listed as still to come.
logos, to_come = {}, set()
for folder in sys.argv[1:]:
    index = json.load(open(os.path.join(folder, "logos.json"), encoding="utf-8"))
    for logo in index["logos"]:
        logos[logo["name"]] = (folder, logo)
    to_come |= {f["name"] for f in index.get("not_in_pack", [])}

entries = []
for folder, logo in logos.values():
    image = Image.open(os.path.join(folder, logo["file"])).convert("RGBA")
    box = image.getchannel("A").getbbox()
    if box:
        image = image.crop(box)
    image.thumbnail((LONGEST, LONGEST), Image.LANCZOS)
    slug = os.path.splitext(logo["file"])[0]
    image.save(os.path.join(OUT_DIR, f"{slug}.webp"), "WEBP", lossless=True, method=6)
    note = logo.get("note") or ""
    entries.append(
        {
            "name": logo["name"],
            "src": f"/images/logos/{slug}.webp",
            "w": image.width,
            "h": image.height,
            # Symbol only: the firm's own site shows its name next to the symbol, so the site does too.
            "mark": note.startswith("Symbol only"),
            # White only: for dark backgrounds; on a light one the site shows the name until a colour file comes.
            "white": bool(logo.get("white_only")),
        }
    )

entries.sort(key=lambda e: e["name"].lower())
lines = []
for e in entries:
    extra = ("mark: true, " if e["mark"] else "") + ("white: true, " if e["white"] else "")
    lines.append(f'  {json.dumps(e["name"], ensure_ascii=False)}: {{ src: "{e["src"]}", w: {e["w"]}, h: {e["h"]}, {extra}}},')
missing = sorted(to_come - set(logos))

with open("src/data/logos.ts", "w", encoding="utf-8") as out:
    out.write(
        "// Generated by tools/import-logos.py from the logo pack (club Drive). Do not edit by hand.\n"
        "// Each firm's current logo, as the firm's own website shows it, trimmed and scaled for the site.\n\n"
        "export type Logo = {\n"
        "  src: string;\n"
        "  /** Pixel size of the file: the logo's proportions. */\n"
        "  w: number;\n"
        "  h: number;\n"
        "  /** Only a symbol: show the firm's name next to it. */\n"
        "  mark?: true;\n"
        "  /** Only in white: for dark backgrounds. */\n"
        "  white?: true;\n"
        "};\n\n"
        "export const LOGOS: Record<string, Logo> = {\n" + "\n".join(lines).replace(", }", " }") + "\n};\n\n"
        "/** Firms whose logo is still to come: the site shows their name in text. */\n"
        f"export const LOGOS_TO_COME = {json.dumps(missing, ensure_ascii=False, indent=2)};\n"
    )
print(f"Wrote {len(entries)} logos to {OUT_DIR} and src/data/logos.ts ({len(missing)} still to come)")
