// Builds src/data/members.ts from the member form export, so the team is regenerated each year
// rather than retyped. Usage:
//   node tools/import-members.mjs ~/Documents/emfc-private/content/2026-11-05
// The content package is private (club Drive): keep it out of this repository, which is public.
// Reads members.json (the form, in site order) and kept-members.json (people kept from the old
// site), applies the site's naming decisions and the title, desk, firm and name changes in
// role-changes.json, and writes one typed list. Emails are never copied.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("Usage: node tools/import-members.mjs <content package folder, e.g. ~/Documents/emfc-private/content/2026-11-02>");
  process.exit(1);
}
const form = JSON.parse(readFileSync(join(dir, "members.json"), "utf8")).members;
const kept = JSON.parse(readFileSync(join(dir, "kept-members.json"), "utf8")).members;
const roleChangesFile = join(dir, "role-changes.json");
const roleChanges = existsSync(roleChangesFile) ? JSON.parse(readFileSync(roleChangesFile, "utf8")).changes : [];
const overrides = Object.fromEntries(
  JSON.parse(readFileSync(join(dir, "photo-overrides.json"), "utf8")).overrides.map((o) => [o.slug, o.photo]),
);

// The form's department names. Marketing was called Brand on the site from 2 to 4 November 2026;
// it is Marketing again, with the form's own titles.
const DEPARTMENTS = {
  "Co-Presidents": "co-presidents",
  "Investment Banking": "investment-banking",
  "Private Markets": "private-markets",
  "Asset Management": "asset-management",
  "Fixed Income": "fixed-income",
  "Corporate Relations": "corporate-relations",
  Marketing: "marketing",
  "Advisory Board": "advisory-board",
};
const POSITIONS = {
  "Co-President": "co-president",
  "Head of Department": "head",
  "Chief Investment Officer": "cio",
  "Vice-President (VP)": "vice-president",
  Associate: "associate",
  Advisor: "advisor",
};
const slugify = (s) =>
  s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const toMember = (p) => {
  const department = DEPARTMENTS[p.department];
  const position = POSITIONS[p.position];
  if (!department || !position) throw new Error(`Unknown department or position for ${p.name}`);
  return {
    name: p.name,
    ...(p.display_name ? { displayName: p.display_name } : {}),
    slug: slugify(p.name),
    title: p.title,
    department,
    position,
    ...(p.desk ? { desk: slugify(p.desk) } : {}),
    ...(p.group ? { group: p.group } : {}),
    ...(p.programme_display ? { programme: p.programme_display } : {}),
    ...(p.linkedin ? { linkedin: p.linkedin } : {}),
    firms: (p.firms ?? []).slice(0, 3),
    ...(p.site_photo_path && p.photo_status !== "replace" ? { photo: p.site_photo_path } : {}),
    ...(p.use_current_site_photo ? { photo: p.use_current_site_photo } : {}),
  };
};

const members = form.map(toMember);
for (const m of members) if (overrides[m.slug]) m.photo = overrides[m.slug];
for (const k of kept) {
  const at = members.findIndex((m) => m.name === (k.after ?? k.before));
  if (at === -1) throw new Error(`Cannot place ${k.name}`);
  const m = toMember({ ...k, firms: [] });
  if (overrides[m.slug]) m.photo = overrides[m.slug];
  members.splice(k.after ? at + 1 : at, 0, m);
}
for (const c of roleChanges) {
  const m = members.find((x) => x.slug === c.slug);
  if (!m) throw new Error(`role-changes.json: no member ${c.slug}`);
  if (c.title) m.title = c.title;
  if (c.firms) m.firms = c.firms.slice(0, 3);
  if (c.desk === null) delete m.desk;
  else if (c.desk) m.desk = slugify(c.desk);
  if (c.display_name === null) delete m.displayName;
  else if (c.display_name) m.displayName = c.display_name;
}

const out = `// Generated by tools/import-members.mjs from the content package ${basename(dir)} (members.json, club Drive).
// Do not edit by hand: change the source files and run \`node tools/import-members.mjs <folder>\`.

export type Position = "co-president" | "head" | "cio" | "vice-president" | "associate" | "advisor";

export type Member = {
  name: string;
  /** How the name reads on the site when it differs from \`name\` (for example with a designation). */
  displayName?: string;
  slug: string;
  title: string;
  /** Department slug, or "co-presidents" / "advisory-board". */
  department: string;
  position: Position;
  /** Desk slug inside the department, when the member has one. */
  desk?: string;
  /** Fixed Income only: "Public credit" or "Private credit". */
  group?: string;
  programme?: string;
  linkedin?: string;
  /** Up to three firms, most important first, as the member listed them. */
  firms: string[];
  /** Portrait path under /public. Missing until the member sends a usable photo. */
  photo?: string;
};

export const MEMBERS: Member[] = ${JSON.stringify(members, null, 2)};
`;
writeFileSync("src/data/members.ts", out);
console.log(`Wrote ${members.length} members to src/data/members.ts`);
